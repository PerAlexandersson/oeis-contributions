#!/usr/bin/env python3
"""Validate OEIS contribution proposals, regenerate their data and write the index.

Usage:
  python3 scripts/validate.py                 # validate every proposals/*.toml
  python3 scripts/validate.py --index         # also rewrite PROPOSALS.md
  python3 scripts/validate.py --bfiles DIR    # also write b-files (n a(n)) for proposals with data
  python3 scripts/validate.py --bfile-terms N # number of terms in b-files (default 1000)

Python 3.11+ standard library only.  Exit status 1 when any proposal is invalid.
"""
import argparse
import re
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
KINDS = {"new-sequence", "comment", "formula", "example", "program", "link", "crossref", "bfile", "correction"}
STATUSES = ["draft", "ready", "submitted", "accepted", "withdrawn"]
EVIDENCE = {"proved", "proof-draft", "experimental", "conjectural"}
LAYOUTS = {"list", "tabl", "tabf"}
DATA_LIMIT = 260  # characters of comma-separated terms shown in %S/%T/%U
A_NUMBER = re.compile(r"^A\d{6}$")


def run_generator(data, extra_args=()):
    cmd = [sys.executable, str(ROOT / data["generator"]), *data.get("args", []), *extra_args]
    out = subprocess.run(cmd, capture_output=True, text=True, check=True, timeout=600).stdout.strip()
    return [t.strip() for t in out.split(",") if t.strip()]


def check(path):
    errors = []
    try:
        p = tomllib.loads(path.read_text())
    except tomllib.TOMLDecodeError as e:
        return None, [f"TOML parse error: {e}"]
    need = ["id", "kind", "target", "status", "evidence", "summary", "authors"]
    errors += [f"missing field `{k}`" for k in need if k not in p]
    if errors:
        return p, errors
    if p["id"] != path.stem:
        errors.append(f"id `{p['id']}` must equal the file name `{path.stem}`")
    if p["kind"] not in KINDS:
        errors.append(f"unknown kind `{p['kind']}`")
    if p["status"] not in STATUSES:
        errors.append(f"unknown status `{p['status']}`")
    if p["evidence"] not in EVIDENCE:
        errors.append(f"unknown evidence `{p['evidence']}`")
    if p["target"] != "new" and not A_NUMBER.match(p["target"]):
        errors.append(f"target must be an A-number or `new`, got `{p['target']}`")
    if p["kind"] == "new-sequence":
        if p["target"] != "new" and p["status"] != "accepted":
            errors.append("a new-sequence proposal has target `new` until accepted")
        for k in ("oeis_search", "data", "oeis"):
            if k not in p:
                errors.append(f"new-sequence needs a [{k}] table")
        o = p.get("oeis", {})
        for k in ("name", "keywords"):
            if k not in o:
                errors.append(f"[oeis] needs `{k}`")
        if "$" in o.get("name", "") or "\\" in o.get("name", ""):
            errors.append("[oeis] name must not contain TeX")
    if p["kind"] == "correction" and "correction" not in p:
        errors.append("correction needs a [correction] table")
    if p["status"] in ("submitted", "accepted") and "submitted" not in p:
        errors.append("submitted/accepted proposals record the `submitted` date")
    if p["status"] == "accepted" and p["kind"] == "new-sequence" and "a_number" not in p:
        errors.append("accepted new sequences record `a_number`")
    data = p.get("data")
    if data:
        for k in ("generator", "offset", "layout", "terms"):
            if k not in data:
                errors.append(f"[data] needs `{k}`")
        if data.get("layout") not in LAYOUTS:
            errors.append(f"[data] layout must be one of {sorted(LAYOUTS)}")
        if "generator" in data and "terms" in data:
            terms = [t.strip() for t in data["terms"].split(",")]
            if len(data["terms"]) > DATA_LIMIT:
                errors.append(f"[data] terms are {len(data['terms'])} characters; OEIS data holds about {DATA_LIMIT}")
            try:
                generated = run_generator(data)
                if generated != terms:
                    errors.append("[data] terms differ from the generator output")
            except (subprocess.SubprocessError, OSError) as e:
                errors.append(f"generator failed: {e}")
    return p, errors


def write_index(proposals):
    lines = ["# Proposals", "", "Generated by `scripts/validate.py --index`; do not edit by hand.", ""]
    for status in STATUSES:
        group = [(path, p) for path, p in proposals if p and p.get("status") == status]
        if not group:
            continue
        lines += [f"## {status.capitalize()} ({len(group)})", "", "| Proposal | Kind | Target | Evidence | Summary |", "|---|---|---|---|---|"]
        for path, p in sorted(group, key=lambda x: x[0].name):
            target = p["target"] if p["target"] == "new" else f"[{p['target']}](https://oeis.org/{p['target']})"
            lines.append(f"| [{p['id']}](proposals/{path.name}) | {p['kind']} | {target} | {p['evidence']} | {p['summary']} |")
        lines.append("")
    (ROOT / "PROPOSALS.md").write_text("\n".join(lines))


def write_bfile(p, directory, n_terms):
    data = p["data"]
    args = list(data.get("args", []))
    terms = run_generator(data)
    if len(terms) < n_terms and "--max-n" in args:
        # Grow the generator range until enough terms exist (rows are appended monotonically).
        i = args.index("--max-n")
        while len(terms) < n_terms:
            args[i + 1] = str(int(args[i + 1]) * 2)
            terms = run_generator({**data, "args": args})
    directory.mkdir(parents=True, exist_ok=True)
    out = directory / f"b-{p['id']}.txt"
    with out.open("w") as f:
        for i, t in enumerate(terms[:n_terms]):
            f.write(f"{data['offset'] + i} {t}\n")
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--index", action="store_true")
    ap.add_argument("--bfiles", type=Path)
    ap.add_argument("--bfile-terms", type=int, default=1000)
    args = ap.parse_args()
    paths = sorted(q for q in (ROOT / "proposals").glob("*.toml") if q.name != "TEMPLATE.toml")
    results, failed = [], False
    for path in paths:
        p, errors = check(path)
        results.append((path, p))
        if errors:
            failed = True
            print(f"FAIL {path.name}")
            for e in errors:
                print(f"  - {e}")
        else:
            print(f"ok   {path.name}")
    if args.index:
        write_index(results)
    if args.bfiles:
        for path, p in results:
            if p and "data" in p:
                print(f"b-file {write_bfile(p, args.bfiles, args.bfile_terms)}")
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
